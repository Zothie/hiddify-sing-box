// DPIVerdict is a gate verdict for the current window.
type DPIVerdict struct {
	TunnelProb    float32
	ReadsAsTunnel bool
}

// DPIGate is the per-session inline gate: a bounded ring of recent packet
// metadata with on-demand verdicts. (The Rust type keeps a per-session map;
// the Go client only ever gates its own single self flow, so the ring is the
// gate.)
type DPIGate struct {
	model     *gbdtModel
	threshold float32
	ring      []PacketMeta // len <= dpiWindow, oldest first
}

func newDPIGate(m *gbdtModel, threshold float32) *DPIGate {
	return &DPIGate{model: m, threshold: threshold}
}

// Record one wire packet for the self flow (O(n) shift at cap, ring of
// dpiWindow — the Rust VecDeque push_back/pop_front semantics).
func (g *DPIGate) Record(wire []byte) {
	m := PacketMetaFromWire(wire)
	if len(g.ring) < dpiWindow {
		g.ring = append(g.ring, m)
		return
	}
	copy(g.ring, g.ring[1:])
	g.ring[dpiWindow-1] = m
}

// Verdict for the current ring, or ok=false until a full window accumulated.
func (g *DPIGate) Verdict() (DPIVerdict, bool) {
	if len(g.ring) < dpiWindow {
		return DPIVerdict{}, false
	}
	x := ExtractFeatures(g.ring)
	prob := TunnelProbability(g.model, &x)
	return DPIVerdict{
		TunnelProb:    prob,
		ReadsAsTunnel: prob > g.threshold,
	}, true
}

// ClientSelfGate is the client-side inline "reads-as-tunnel" self-check
// (aivpn ClientSelfGate). It watches the client's OWN outbound shaped wire;
// when it starts reading as a tunnel it raises a rotate-request (once per
// cooldown) so the tunnel can be rebuilt with a fresh mask before the DPI box
// finishes learning the flow.
type ClientSelfGate struct {
	gate            *DPIGate
	stride          uint32
	seen            uint32
	cooldownWindows uint32
	cooldownLeft    uint32
	// raises counts rotate-requests raised (live diagnostics, asserted by the
	// integration tests).
	raises   uint64
	lastProb float32
}

// Gate-state record for the adaptive snapshot: the process-wide outcome of
// the most recent EnableDPIGate call. The coordinator never owns the gate —
// the outbound layer does — so this is the seam the state reporter reads to
// surface dpi_gate_enabled/dpi_gate_reason.
var (
	dpiGateStateMu     sync.RWMutex
	dpiGateStateOn     bool
	dpiGateStateReason string
)

// GateState reports the client self-check gate status recorded at the most
// recent EnableDPIGate call: enabled is true when the gate is live and
// reason is then empty; otherwise reason carries the failure that kept the
// gate off (fail-to-off diagnostics). Before any EnableDPIGate call both
// are zero.
func GateState() (enabled bool, reason string) {
	dpiGateStateMu.RLock()
	defer dpiGateStateMu.RUnlock()
	return dpiGateStateOn, dpiGateStateReason
}

// EnableDPIGate builds the client self-check gate at the given threshold.
// FAIL-TO-OFF: any embedded-model digest mismatch or malformed blob returns
// an error and the caller must keep running ungated (the historical,
// gate-free behavior) — never with a half-parsed model.
func EnableDPIGate(threshold float32) (*ClientSelfGate, error) {
	m, err := loadDPIGateModel()
	if err != nil {
		dpiGateStateMu.Lock()
		dpiGateStateOn, dpiGateStateReason = false, err.Error()
		dpiGateStateMu.Unlock()
		return nil, err
	}
	dpiGateStateMu.Lock()
	dpiGateStateOn, dpiGateStateReason = true, ""
	dpiGateStateMu.Unlock()
	return &ClientSelfGate{
		gate:            newDPIGate(m, threshold),
		stride:          DPIGateDefaultStride,
		cooldownWindows: DPIGateDefaultCooldownWindows,
	}, nil
}

// WithStride sets the 1-in-stride outbound packet sampling (clamped to >= 1).
func (g *ClientSelfGate) WithStride(stride uint32) *ClientSelfGate {
	if stride < 1 {
		stride = 1
	}
	g.stride = stride
	return g
}

// WithCooldownWindows sets how many sampled packets stay quiet after a raise.
func (g *ClientSelfGate) WithCooldownWindows(windows uint32) *ClientSelfGate {
	g.cooldownWindows = windows
	return g
}

// Raises reports how many rotate-requests the gate has raised.
func (g *ClientSelfGate) Raises() uint64 { return g.raises }

// LastProb reports the tunnel probability of the last raise.
func (g *ClientSelfGate) LastProb() float32 { return g.lastProb }

// Observe feeds one outbound wire datagram. The second result reports a
// rotate-request (sampling + cooldown applied internally); the first is the
// tunnel probability of that raise.
func (g *ClientSelfGate) Observe(wire []byte) (float32, bool) {
	sample := g.seen%g.stride == 0
	g.seen++ // Rust: wrapping_add — uint32 wraps identically
	if !sample {
		return 0, false
	}
	g.gate.Record(wire)

	if g.cooldownLeft > 0 {
		g.cooldownLeft--
		return 0, false
	}

	verdict, ok := g.gate.Verdict()
	if !ok {
		return 0, false
	}
	if verdict.ReadsAsTunnel {
		g.cooldownLeft = g.cooldownWindows
		g.raises++
		g.lastProb = verdict.TunnelProb
		return verdict.TunnelProb, true
	}
	return 0, false
}

