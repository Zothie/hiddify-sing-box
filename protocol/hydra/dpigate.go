package hydra

// ML-DPI "reads-as-tunnel" gate — Go port of the Rust hydra dpi_gate.rs
// (aivpn ClientSelfGate, wave 3 of the TUNING.md axis sweep; plan
// axis-sweep.md, C1 dpi-gate/threshold).
//
// The embedded GBDT ensemble (120 trees, depth 3, 23 features, window 24)
// approximates an nDPI verdict over a window of sampled outbound wire
// packets: does this UDP flow read as an obfuscated tunnel (Unknown) or as
// its claimed protocol (QUIC/STUN/DNS/WebRTC)?
//
// Parity contract (the acceptance for this port):
//   - the model itself is NOT re-expressed in Go — the canonical binary blob
//     (testdata/dpigate_model.blob) is exported by the Rust crate's
//     dpigate-export bin straight out of src/dpi_gate/model.rs and embedded
//     below (go:embed); EnableDPIGate parses it with float32 thresholds kept
//     verbatim and refuses to enable when the blob digest differs from the
//     parity-verified constant (FAIL-TO-OFF);
//   - feature extraction follows the Rust code operation-for-operation
//     (identical f64/f32 op order, banker's-rounding percentiles, the same
//     QUIC byte0 canonicalization and STUN/DNS root checks);
//   - testdata/dpigate_fixtures.json (500 seeded-random windows + handcrafted
//     edges + a near-threshold boundary sweep, exported by the same Rust bin)
//     is evaluated in dpigate_test.go and requires a 100% verdict match.
//     Anything less keeps the gate compiled but disabled.
//
// Live semantics (Rust tunnel.rs run_rtc_pump): the client samples its own
// outbound rtc wire; when tunnel_prob > threshold it dead-flags the engine
// (RtcPoll.RotateMask says so), the pump kills the tunnel, and the adaptive
// layer rebuilds it with a fresh mask (new salt / ICE credentials / SSRC).

import (
	"crypto/sha256"
	"encoding/base64"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"fmt"
	"math"
	"slices"
	"sync"
)

const (
	// dpiWindow is the sliding window length in packets (training N = 24).
	dpiWindow = 24
	// dpiNFeatures is the feature count the embedded model was fit on.
	dpiNFeatures = 23
	// DPIGateDefaultThreshold matches the Rust client's env default.
	DPIGateDefaultThreshold = 0.5
	// DPIGateDefaultStride / DPIGateDefaultCooldownWindows mirror
	// ClientSelfGate::DEFAULT_STRIDE / DEFAULT_COOLDOWN_WINDOWS: every 16th
	// outbound packet is sampled; after a raise the gate stays quiet for 8
	// sampled packets.
	DPIGateDefaultStride          = 16
	DPIGateDefaultCooldownWindows = 8
)

// dpiGateBlobSHA256 is the SHA-256 of the canonical model blob this build was
// parity-verified against (fixtures: testdata/dpigate_fixtures.json, exported
// by hydra src/bin/dpigate-export.rs). EnableDPIGate refuses to enable when
// the embedded blob's digest differs — a model edited without re-running the
// Rust parity export is a gate that silently goes OFF, never one that lies.
const dpiGateBlobSHA256 = "888c1e4f7883fc8daf759ca6810ffefe6a13825819dc6e78e9601cd32a450541"

var (
	dpiGateBlobOnce sync.Once
	dpiGateBlob     []byte
	dpiGateBlobErr  error
)

// dpiGateModelBytes decodes the canonical model blob (the base64 const in
// dpigate_model_gen.go, generated by the Rust exporter — no binary file in
// the tree to lose) and digest-verifies it against the parity-verified
// constant. Fail-to-off: a decode failure or digest mismatch surfaces as an
// error at EnableDPIGate, never as a half-verified model.
func dpiGateModelBytes() ([]byte, error) {
	dpiGateBlobOnce.Do(func() {
		b, err := base64.StdEncoding.DecodeString(dpiGateModelBlobB64)
		if err != nil {
			dpiGateBlobErr = fmt.Errorf("hydra dpi-gate: corrupt embedded model const: %w", err)
			return
		}
		sum := sha256.Sum256(b)
		if got := hex.EncodeToString(sum[:]); got != dpiGateBlobSHA256 {
			dpiGateBlobErr = fmt.Errorf(
				"hydra dpi-gate: embedded model digest %s does not match the parity-verified %s; gate stays OFF (re-export fixtures from the Rust crate and re-verify)",
				got, dpiGateBlobSHA256)
			return
		}
		dpiGateBlob = b
	})
	return dpiGateBlob, dpiGateBlobErr
}

