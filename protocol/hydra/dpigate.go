// Verbatim model parse
// ---------------------------------------------------------------------------

// gbdtNode is one flattened GradientBoosting node. Internal: feature >= 0 —
// descend left if x[feature] <= threshold, else right. Leaf: feature == -1 —
// contribute value to the raw score.
type gbdtNode struct {
	feature   int16
	threshold float32
	left      uint16
	right     uint16
	value     float32
}

// gbdtModel is the parsed ensemble. Thresholds/values stay float32 bit-exact:
// they arrive as raw LE bit patterns and are never re-rounded.
type gbdtModel struct {
	schema      uint32
	init        float32
	learnRate   float32
	nodes       []gbdtNode
	treeOffsets []uint32
}

var (
	dpiGateModelOnce sync.Once
	dpiGateModel     *gbdtModel
	dpiGateModelErr  error
)

// loadDPIGateModel parses the digest-verified blob once.
func loadDPIGateModel() (*gbdtModel, error) {
	blob, err := dpiGateModelBytes()
	if err != nil {
		return nil, err
	}
	dpiGateModelOnce.Do(func() {
		dpiGateModel, dpiGateModelErr = parseGbdtBlob(blob)
	})
	return dpiGateModel, dpiGateModelErr
}

var errDPIGateBlob = errors.New("hydra dpi-gate: malformed model blob")

// parseGbdtBlob reads the canonical LE blob the Rust exporter writes:
//
//	"DPG1" | u32 n_features | u32 n_trees | u32 schema | f32 init | f32 lr |
//	u32 node_count | node_count * (i16 feature | f32 threshold | u16 left |
//	u16 right | f32 value) — 14 bytes per node — | u32 offset_count |
//	offset_count * u32
func parseGbdtBlob(b []byte) (*gbdtModel, error) {
	bad := func(why string) (*gbdtModel, error) { return nil, fmt.Errorf("%w: %s", errDPIGateBlob, why) }
	if len(b) < 24 || string(b[:4]) != "DPG1" {
		return bad("bad magic/length")
	}
	le := binary.LittleEndian
	m := &gbdtModel{
		schema: le.Uint32(b[12:16]),
		init:   math.Float32frombits(le.Uint32(b[16:20])),
	}
	m.learnRate = math.Float32frombits(le.Uint32(b[20:24]))
	nFeatures := le.Uint32(b[4:8])
	nTrees := le.Uint32(b[8:12])
	if nFeatures != dpiNFeatures || nTrees == 0 {
		return bad("feature/tree count mismatch")
	}
	off := 24
	nodeCount := int(le.Uint32(b[off : off+4]))
	off += 4
	if nodeCount == 0 || nodeCount > 1<<20 || len(b)-off < nodeCount*14 {
		return bad("node table truncated")
	}
	m.nodes = make([]gbdtNode, nodeCount)
	for i := range m.nodes {
		n := &m.nodes[i]
		n.feature = int16(le.Uint16(b[off : off+2]))
		n.threshold = math.Float32frombits(le.Uint32(b[off+2 : off+6]))
		n.left = le.Uint16(b[off+6 : off+8])
		n.right = le.Uint16(b[off+8 : off+10])
		n.value = math.Float32frombits(le.Uint32(b[off+10 : off+14]))
		if (n.feature < 0 && n.feature != -1) || int(n.feature) >= dpiNFeatures {
			return bad("node feature out of range")
		}
		if n.feature >= 0 && (int(n.left) >= nodeCount || int(n.right) >= nodeCount) {
			return bad("node child index out of range")
		}
		off += 14
	}
	offsetCount := int(le.Uint32(b[off : off+4]))
	off += 4
	if offsetCount != int(nTrees)+1 || len(b)-off < offsetCount*4 {
		return bad("tree offset table truncated")
	}
	m.treeOffsets = make([]uint32, offsetCount)
	for i := range m.treeOffsets {
		m.treeOffsets[i] = le.Uint32(b[off : off+4])
		off += 4
		if int(m.treeOffsets[i]) > nodeCount {
			return bad("tree offset out of range")
		}
	}
	if m.treeOffsets[0] != 0 || m.treeOffsets[offsetCount-1] != uint32(nodeCount) {
		return bad("tree offsets do not cover the node table")
	}
	if off != len(b) {
		return bad("trailing bytes")
	}
	return m, nil
}

// ---------------------------------------------------------------------------
// Packet metadata — the extractor's per-packet input (dpi_gate.rs PacketMeta)
// ---------------------------------------------------------------------------

// dpiSizeBins is the size histogram bins [lo, hi), identical to the training
// features.py. NOTE the last bin excludes 65535 exactly like the Rust table.
var dpiSizeBins = [6][2]uint32{
	{0, 100},
	{100, 300},
	{300, 600},
	{600, 1000},
	{1000, 1400},
	{1400, 65535},
}

// PacketMeta is the cheap per-packet metadata everything the 23 features
// need — no payload kept.
type PacketMeta struct {
	Len      uint16
	Byte0    uint8
	HasByte0 bool
	// StunType is the STUN message type at offset 0 with the STUN/RTP demux
	// bits clear.
	StunType bool
	// MagicOK is the STUN magic cookie 21 12 A4 42 at offset 4.
	MagicOK bool
	// StunLenOK is msg_len + 20 == payload_len — nDPI's is_stun() root check.
	StunLenOK bool
	// DNSOK is the rough DNS query heuristic qdcount == 1 && ancount <= 16.
	DNSOK bool
	// Ent16 is the Shannon entropy (bits/byte) of the first 16 wire bytes.
	Ent16 float32
	// EntFull is the Shannon entropy of the whole wire packet.
	EntFull float32
}

// PacketMetaFromWire extracts the metadata from the observable wire bytes of
// one packet — exactly what a DPI box inspects. Bit-exact twin of Rust
// PacketMeta::from_wire.
func PacketMetaFromWire(p []byte) PacketMeta {
	n := len(p)
	rawByte0 := byte(0)
	if n > 0 {
		rawByte0 = p[0]
	}
	// QUIC short-header spin/protected bits carry no feature information.
	byte0 := rawByte0
	if rawByte0&0xc0 == 0x40 {
		byte0 = 0x40
	}

	stunType := false
	if n >= 2 && p[0]&0xC0 == 0 {
		stunType = dpiStunTypeMatch(p[0], p[1])
	}
	magicOK := n >= 8 && p[4] == 0x21 && p[5] == 0x12 && p[6] == 0xA4 && p[7] == 0x42
	stunLenOK := false
	if n >= 4 {
		msgLen := int(p[2])<<8 | int(p[3])
		stunLenOK = msgLen+20 == n
	}
	dnsOK := false
	if n >= 12 {
		qd := int(p[4])<<8 | int(p[5])
		an := int(p[6])<<8 | int(p[7])
		dnsOK = qd == 1 && an <= 16
	}

	n16 := n
	if n16 > 16 {
		n16 = 16
	}
	len16 := uint16(n)
	if n > 0xffff {
		len16 = 0xffff
	}
	return PacketMeta{
		Len:       len16,
		Byte0:     byte0,
		HasByte0:  n > 0,
		StunType:  stunType,
		MagicOK:   magicOK,
		StunLenOK: stunLenOK,
		DNSOK:     dnsOK,
		Ent16:     float32(dpiShannonEntropy(p[:n16], byte0)),
		EntFull:   float32(dpiShannonEntropy(p, byte0)),
	}
}

func dpiStunTypeMatch(b0, b1 byte) bool {
	return (b0 == 0x00 && b1 == 0x01) || (b0 == 0x01 && b1 == 0x01) ||
		(b0 == 0x00 && b1 == 0x03) || (b0 == 0x01 && b1 == 0x11)
}

// dpiShannonEntropy mirrors Rust shannon_entropy exactly: the raw first byte
// is dropped from the histogram and replaced by the canonical one; the f64
// accumulation order (counts 0..256) and math.Log2 use are load-bearing.
func dpiShannonEntropy(data []byte, first byte) float64 {
	if len(data) == 0 {
		return 0
	}
	var counts [256]uint32
	for _, b := range data {
		counts[b]++
	}
	counts[data[0]]--
	counts[first]++
	length := float64(len(data))
	h := 0.0
	for i := range counts {
		if counts[i] > 0 {
			p := float64(counts[i]) / length
			h -= p * math.Log2(p)
		}
	}
	return h
}

// dpiRoundHalfEven is round-half-to-even (banker's rounding) — matches the
// Python round() the training feature pipeline used. Load-bearing for
// percentile parity.
func dpiRoundHalfEven(x float64) float64 {
	f := math.Floor(x)
	diff := x - f
	if diff < 0.5 {
		return f
	} else if diff > 0.5 {
		return f + 1.0
	} else if int64(f)%2 == 0 {
		return f
	}
	return f + 1.0
}

// dpiPct indexes a sorted size slice at idx = round_half_even(q*(n-1)),
// clamped to the last element.
func dpiPct(sorted []uint32, q float64) float32 {
	if len(sorted) == 0 {
		return 0
	}
	idx := int(dpiRoundHalfEven(q * float64(len(sorted)-1)))
	if idx > len(sorted)-1 {
		idx = len(sorted) - 1
	}
	return float32(sorted[idx])
}

// ExtractFeatures pulls the 23-feature vector from a packet window in the
// exact order the embedded model consumes it (the Rust port of the training
// features.py::vector with the two IAT features dropped). All-zero for an
// empty window. The op order mirrors dpi_gate.rs op-for-op: f64 means and
// variances, f32 casts at the same points, banker's-rounded percentiles.
func ExtractFeatures(window []PacketMeta) [dpiNFeatures]float32 {
	var f [dpiNFeatures]float32
	n := len(window)
	if n == 0 {
		return f
	}
	nf := float32(n)

	sizes := make([]uint32, n)
	var sum float64
	for i, m := range window {
		sizes[i] = uint32(m.Len)
	}
	for _, s := range sizes {
		sum += float64(s)
	}
	mean := sum / float64(n)
	var sq float64
	for _, s := range sizes {
		d := float64(s) - mean
		sq += d * d
	}
	variance := sq / float64(n)
	slices.Sort(sizes)

	f[0] = nf                           // n_pkts
	f[1] = float32(mean)                // sz_mean
	f[2] = float32(math.Sqrt(variance)) // sz_std
	f[3] = float32(sizes[0])            // sz_min
	f[4] = float32(sizes[n-1])          // sz_max
	f[5] = dpiPct(sizes, 0.5)           // sz_med
	f[6] = dpiPct(sizes, 0.10)          // sz_p10
	f[7] = dpiPct(sizes, 0.90)          // sz_p90

	var binc [len(dpiSizeBins)]uint32
	for i := range window {
		s := uint32(window[i].Len)
		for j, b := range dpiSizeBins {
			if s >= b[0] && s < b[1] {
				binc[j]++
				break
			}
		}
	}
	for i := range binc {
		f[8+i] = float32(binc[i]) / nf // szfrac_*
	}

	var ent16Sum, entFullSum float64
	for i := range window {
		ent16Sum += float64(window[i].Ent16)
		entFullSum += float64(window[i].EntFull)
	}
	f[14] = float32(ent16Sum / float64(n))
	f[15] = float32(entFullSum / float64(n))

	var b0Sum uint64
	var b0N, b0Msb, quicLong uint32
	for i := range window {
		m := &window[i]
		if m.HasByte0 {
			b0Sum += uint64(m.Byte0)
			b0N++
			if m.Byte0&0x80 != 0 {
				b0Msb++
			}
			if m.Byte0&0xC0 == 0xC0 {
				quicLong++
			}
		}
	}
	if b0N > 0 {
		f[16] = float32(b0Sum) / float32(b0N)
		f[17] = float32(b0Msb) / float32(b0N)
		f[18] = float32(quicLong) / float32(b0N)
	}

	for i := range window {
		if window[i].StunType {
			f[19]++
		}
		if window[i].MagicOK {
			f[20]++
		}
		if window[i].StunLenOK {
			f[21]++
		}
		if window[i].DNSOK {
			f[22]++
		}
	}
	f[19] = f[19] / nf
	f[20] = f[20] / nf
	f[21] = f[21] / nf
	f[22] = f[22] / nf

	return f
}

// TunnelProbability runs the embedded ensemble; returns P(window reads as
// tunnel). raw = INIT + lr * sum(leaf), then a logistic squash.
func TunnelProbability(m *gbdtModel, x *[dpiNFeatures]float32) float32 {
	raw := m.init
	for t := 0; t < len(m.treeOffsets)-1; t++ {
		i := int(m.treeOffsets[t])
		for {
			node := &m.nodes[i]
			if node.feature < 0 {
				raw += m.learnRate * node.value
				break
			}
			if x[node.feature] <= node.threshold {
				i = int(node.left)
			} else {
				i = int(node.right)
			}
		}
	}
	// Rust: 1.0 / (1.0 + (-raw).exp()) — all f32 except the exp itself, which
	// glibc computes as expf; the parity fixtures pin the exact result.
	return 1.0 / (1.0 + float32(math.Exp(float64(-raw))))
}

