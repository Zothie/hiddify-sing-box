// SetDPIGate attaches the client self-gate to the rtc engine. Call before the
// first Poll (before the pump starts) — the gate is sampled from Poll, which
// the rtc pump serializes, so no further synchronization is needed.
func (r *RtcMask) SetDPIGate(g *ClientSelfGate) { r.dpiGate = g }
